#!/usr/bin/env node
// The reference answer for beat 3: Maplewood's October 2026 position computed directly from the
// seed data and the @tax/core rates. Rehearsals compare the agent's numbers against this.
// The agent itself never runs this; it gets there through typed tools.
//
//   node scripts/expected-position.mjs > docs/expected-october-2026.md

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const J = "https://onto.melx.buzz/ns/legal/jurisdictions#";
const TAX = "https://onto.melx.buzz/ns/tax/core#";
const lines = fs.readFileSync(path.join(root, "seed/october-2026.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const profile = JSON.parse(fs.readFileSync(path.join(root, "seed/maplewood.json"), "utf8"));

// The bad rows are excluded, as the agent must exclude them.
const valid = lines.filter((l) => l.placeOfSupply && typeof l.amount === "number");
const excluded = lines.filter((l) => !valid.includes(l));

// [place of supply, tax type] → rate, provision (citation as @legal/acts gives it), authority, deadline id.
// US rates are the state rate only; local rates are not modelled (#14).
const RULES = [
  ["CA-ON", "HST", 0.13, "ETA s.165(2) (excise_tax_act_s165_2)", "CRA", "GST-HST-2026-10"],
  ["CA-QC", "GST", 0.05, "ETA s.165(1) (excise_tax_act_s165)", "CRA", "GST-HST-2026-10"],
  ["CA-QC", "QST", 0.09975, "Act respecting the Québec sales tax s.16 (quebec_sales_tax_s16)", "Revenu Québec", "QST-2026-Q4"],
  ["CA-BC", "GST", 0.05, "ETA s.165(1) (excise_tax_act_s165)", "CRA", "GST-HST-2026-10"],
  ["CA-BC", "PST", 0.07, "PSTA s.105(1) (bc_psta_s105_1)", "BC Ministry of Finance", "PST-2026-10"],
  ["US-NY", "US_SalesTax", 0.04, "NY Tax Law §1105 (ny_tax_law_section1105)", "NY DTF", "ST-NY-2026-SEP-NOV"],
  ["US-WA", "US_SalesTax", 0.065, "RCW 82.08.020 (wa_rcw_82_08_020)", "WA DOR", "ST-WA-2026-10"],
];
const due = Object.fromEntries(profile.deadlines.map((d) => [d["@id"].split("/").pop(), d.dueDate]));
const money = (n) => n.toLocaleString("en-CA", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const out = [
  "# Expected October 2026 position (reference answer)",
  "",
  "Generated by `scripts/expected-position.mjs` from `seed/`. Tax is computed per line and rounded to the cent, then summed. US lines are the state rate only (local rates are not modelled), labelled \"state portion only\". For demonstration, not tax advice.",
  "",
  "| Jurisdiction | Tax type | Lines | Taxable supplies | Rate | Tax | Arises from | Obligee | Due |",
  "| --- | --- | ---: | ---: | ---: | ---: | --- | --- | --- |",
];
for (const [j, t, rate, prov, authority, dl] of RULES) {
  const hit = valid.filter((l) => l.placeOfSupply === J + j && l.taxType.includes(TAX + t));
  const base = hit.reduce((s, l) => s + l.amount, 0);
  const tax = hit.reduce((s, l) => s + Math.round(l.amount * rate * 100) / 100, 0);
  const cur = j.startsWith("US") ? "USD" : "CAD";
  out.push(`| ${j} | ${t.replace("US_SalesTax", "Sales tax (state portion only)")} | ${hit.length} | ${cur} ${money(base)} | ${(rate * 100).toFixed(3).replace(/\.?0+$/, "")}% | ${cur} ${money(tax)} | ${prov} | ${authority} | ${due[dl]} |`);
}
const qcB2B = valid.filter((l) => l.placeOfSupply === J + "CA-QC" && l.recipientIsRegistrant).length;
out.push(
  "",
  `Quebec: ${qcB2B} lines go to QST-registered businesses. Under the specified system, Maplewood charges them GST only, no QST.`,
  "",
  "**Excluded (schema rejections):**",
  ...excluded.map((l) => `- ${l["@id"].split("/").pop()}: ${!l.placeOfSupply ? "no placeOfSupply" : `amount is ${JSON.stringify(l.amount)}`}`),
  "- `rates.jsonl` PST-BC-promo: no effectiveFrom (the rate is excluded; the line items use the @tax/core rate)",
);
console.log(out.join("\n"));
